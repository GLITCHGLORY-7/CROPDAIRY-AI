// CropDiary AI — Gemini Assistant Adapter & Supabase Edge Function Integration Vitest Suite
import { describe, it, expect, beforeEach, vi, afterEach } from 'vitest';
import { GeminiAssistantAdapter } from '@/features/assistant/services/geminiAssistantAdapter';
import { FarmContextPayload } from '@/types/assistant';
import { assistantService } from '@/features/assistant/services/assistantService';

// Mock Supabase Client
let mockInvokeResponse = {
  data: null as any,
  error: null as any,
};
let mockIsConfigured = true;
let mockInvokeFn = vi.fn(async (_fnName: string, _options: any) => mockInvokeResponse);

vi.mock('@/services/supabaseClient', () => ({
  get isSupabaseConfigured() {
    return () => mockIsConfigured;
  },
  get supabase() {
    if (!mockIsConfigured) return null;
    return {
      functions: {
        invoke: (...args: any[]) => mockInvokeFn(...args),
      },
    };
  },
}));

describe('Gemini Assistant Adapter & Server-Side Edge Function Integration', () => {
  const dummyContext: FarmContextPayload = {
    farms: [{ id: 'farm-1', name: 'Cauvery Delta Orchard', location: 'Thanjavur, Tamil Nadu', totalArea: 4.5 }],
    plots: [{ id: 'plot-1', name: 'North Plot', area: 4.5, soilType: 'Alluvial Loam' }],
    activeCropPlans: [{ id: 'plan-1', cropName: 'Paddy CR-1009', season: 'Samba', sowingDate: '2026-08-15' }],
    recentActivities: [],
    recentExpenses: [],
    recentHarvests: [],
    recentSales: [],
    budgets: [],
    weatherAlerts: [],
    recentAssessments: [],
  };

  let warnSpy: any;

  beforeEach(() => {
    mockIsConfigured = true;
    mockInvokeResponse = { data: null, error: null };
    mockInvokeFn = vi.fn(async (_fnName: string, _options: any) => mockInvokeResponse);
    warnSpy = vi.spyOn(console, 'warn').mockImplementation(() => {});
  });

  afterEach(() => {
    warnSpy.mockRestore();
    vi.restoreAllMocks();
  });

  it('1. Successfully invokes gemini-assistant edge function and parses response', async () => {
    mockInvokeResponse = {
      data: {
        content: 'For Paddy CR-1009 in Samba season, monitor for leaf folder and apply neem oil at 3% or chlorantraniliprole 18.5 SC at 60 ml/acre.',
        modelName: 'gemini-2.5-flash',
        sources: [
          {
            recordType: 'crop_doctor',
            recordId: 'gemini-icar-guidance',
            title: 'Google Gemini 2.5 Flash Precision Agronomy & ICAR Guidelines',
          },
        ],
        disclaimer: 'Generated by CropDiary AI powered by Google Gemini 2.5 Flash, grounded in your real-time farm records.',
      },
      error: null,
    };

    const adapter = new GeminiAssistantAdapter();
    const result = await adapter.generateResponse('How to manage leaf folder in Paddy?', dummyContext, 'en');

    expect(mockInvokeFn).toHaveBeenCalledWith('gemini-assistant', {
      body: {
        userMessage: 'How to manage leaf folder in Paddy?',
        farmContext: dummyContext,
        language: 'en',
      },
    });

    expect(result).toBeDefined();
    expect(result.content).toContain('Paddy CR-1009');
    expect(result.modelName).toBe('gemini-2.5-flash');
    expect(result.usedFarmerRecords).toBe(true);
    expect(result.disclaimer).toContain('Google Gemini 2.5 Flash');
    expect(warnSpy).not.toHaveBeenCalled();
  });

  it('2. Gracefully falls back to ICAR agronomy when Supabase is unconfigured (offline mode)', async () => {
    mockIsConfigured = false;

    const adapter = new GeminiAssistantAdapter();
    const result = await adapter.generateResponse('How to improve soil organic carbon?', dummyContext, 'en');

    expect(mockInvokeFn).not.toHaveBeenCalled();
    expect(result).toBeDefined();
    expect(result.disclaimer).toContain('offline / rulebase mode');
    expect(warnSpy).toHaveBeenCalledWith(
      expect.stringContaining('Local development mode')
    );
  });

  it('3. Handles upstream 429 quota exceeded error and activates rulebase fallback', async () => {
    mockInvokeResponse = {
      data: null,
      error: { status: 429, message: 'Google Gemini rate limit or quota exceeded' },
    };

    const adapter = new GeminiAssistantAdapter();
    const result = await adapter.generateResponse('Best irrigation practice for alluvial soil?', dummyContext, 'en');

    expect(result).toBeDefined();
    expect(result.disclaimer).toContain('offline / rulebase mode');
    expect(warnSpy).toHaveBeenCalledWith(
      expect.stringContaining('Quota exceeded')
    );
  });

  it('4. Handles 403 authorization error safely without leaking secrets', async () => {
    mockInvokeResponse = {
      data: null,
      error: { status: 403, message: 'Origin or credentials rejected by CORS/policy' },
    };

    const adapter = new GeminiAssistantAdapter();
    const result = await adapter.generateResponse('Check fertilizer dosage', dummyContext, 'en');

    expect(result).toBeDefined();
    expect(result.disclaimer).toContain('offline / rulebase mode');
    expect(warnSpy).toHaveBeenCalledWith(
      expect.stringContaining('Access forbidden')
    );
  });

  it('5. Handles 503 service unavailable (missing GEMINI_API_KEY) and falls back safely', async () => {
    mockInvokeResponse = {
      data: null,
      error: { status: 503, message: 'GEMINI_API_KEY unconfigured or upstream unreachable' },
    };

    const adapter = new GeminiAssistantAdapter();
    const result = await adapter.generateResponse('Check fertilizer dosage', dummyContext, 'en');

    expect(result).toBeDefined();
    expect(result.disclaimer).toContain('offline / rulebase mode');
    expect(warnSpy).toHaveBeenCalledWith(
      expect.stringContaining('Service unavailable')
    );
  });

  it('6. Handles network exceptions / Edge function communication failure gracefully', async () => {
    mockInvokeFn.mockRejectedValue(new Error('Edge function fetch failure'));

    const adapter = new GeminiAssistantAdapter();
    const result = await adapter.generateResponse('Drip irrigation schedule', dummyContext, 'en');

    expect(result).toBeDefined();
    expect(result.disclaimer).toContain('offline / rulebase mode');
    expect(warnSpy).toHaveBeenCalledWith(
      expect.stringContaining('Network failure')
    );
  });

  it('7. Produces Tamil localized transparent disclaimer when falling back', async () => {
    mockInvokeResponse = {
      data: null,
      error: { status: 503 },
    };

    const adapter = new GeminiAssistantAdapter();
    const result = await adapter.generateResponse('வணக்கம்', dummyContext, 'ta');

    expect(result).toBeDefined();
    expect(result.disclaimer).toContain('உள்ளூர் ICAR / TNAU வழிகாட்டுதல்');
  });

  it('8. Confirms Gemini-primary provider selection in assistantService', () => {
    const adapter = new GeminiAssistantAdapter();
    expect(adapter.isAvailable()).toBe(true);
    expect(adapter.adapterName).toBe('gemini-2.5-flash-agricultural-assistant');
  });
});
