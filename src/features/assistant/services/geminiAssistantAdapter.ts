// CropDiary AI — Secure Google Gemini AI Assistant Adapter (via Supabase Edge Function)
import { IAIAssistantAdapter } from './IAIAssistantAdapter';
import {
  FarmContextPayload,
  AssistantResponsePayload,
  Language,
} from '@/types/assistant';
import {
  logSanitizedDiagnostic as baseLogSanitizedDiagnostic,
  createLocalIcarFallbackResponse,
} from './assistantFallbackHelper';
import { supabase, isSupabaseConfigured } from '@/services/supabaseClient';

const PROVIDER_LABEL = 'CropDiary AI Gemini Assistant';

function logSanitizedDiagnostic(category: string, detail?: string): void {
  baseLogSanitizedDiagnostic(category, detail, PROVIDER_LABEL);
}

export class GeminiAssistantAdapter implements IAIAssistantAdapter {
  readonly adapterName = 'gemini-2.5-flash-agricultural-assistant';

  isAvailable(): boolean {
    return isSupabaseConfigured();
  }

  async generateResponse(
    userMessage: string,
    farmContext: FarmContextPayload,
    language: Language = 'en'
  ): Promise<AssistantResponsePayload> {
    if (!isSupabaseConfigured() || !supabase) {
      logSanitizedDiagnostic('Local development mode', 'Supabase credentials unconfigured');
      return this.renderFallbackResponse(userMessage, farmContext, language);
    }

    try {
      const { data, error } = await supabase.functions.invoke('gemini-assistant', {
        body: {
          userMessage,
          farmContext,
          language,
        },
      });

      if (!error && data?.content && typeof data.content === 'string') {
        return {
          content: data.content,
          sources: data.sources || [
            {
              recordType: 'crop_doctor',
              recordId: 'gemini-icar-guidance',
              title: 'Google Gemini 2.5 Flash Precision Agronomy & ICAR Guidelines',
            },
          ],
          modelName: data.modelName || 'gemini-2.5-flash',
          usedFarmerRecords: true,
          disclaimer:
            data.disclaimer ||
            (language === 'ta'
              ? 'பயிர் நாட்குறிப்பு AI: Google Gemini 2.5 Flash மற்றும் உங்கள் பண்ணை பதிவுகள் அடிப்படையில் உருவாக்கப்பட்டது.'
              : 'Generated by CropDiary AI powered by Google Gemini 2.5 Flash, grounded in your real-time farm records.'),
        };
      }

      // Safe, categorized failure diagnostics
      if (error) {
        const status = (error as any)?.context?.status || (error as any)?.status;
        if (status === 401) {
          logSanitizedDiagnostic('Authentication required', 'User must sign in with an active session');
        } else if (status === 403) {
          logSanitizedDiagnostic('Access forbidden', 'Origin or credentials rejected by CORS/policy');
        } else if (status === 404) {
          logSanitizedDiagnostic('Service not found', 'Edge Function not deployed on Supabase');
        } else if (status === 429) {
          logSanitizedDiagnostic('Quota exceeded', 'Google Gemini rate limit or quota exceeded (HTTP 429)');
        } else if (status === 503) {
          logSanitizedDiagnostic('Service unavailable', 'GEMINI_API_KEY unconfigured or upstream unreachable');
        } else if (status === 502) {
          logSanitizedDiagnostic('Malformed response', 'Invalid response structure from upstream provider');
        } else {
          logSanitizedDiagnostic('Provider error', typeof status === 'number' ? `HTTP ${status}` : 'Unknown status');
        }
      } else if (!data?.content) {
        logSanitizedDiagnostic('Empty response', 'Gemini model returned zero text');
      }

      return this.renderFallbackResponse(userMessage, farmContext, language);
    } catch (networkErr: any) {
      const isOffline = typeof navigator !== 'undefined' && !navigator.onLine;
      const isTimeout = networkErr?.name === 'AbortError';
      logSanitizedDiagnostic(
        isOffline ? 'Device offline' : isTimeout ? 'Request timed out' : 'Network failure',
        networkErr?.name || 'FetchError'
      );
      return this.renderFallbackResponse(userMessage, farmContext, language);
    }
  }

  private async renderFallbackResponse(
    userMessage: string,
    farmContext: FarmContextPayload,
    language: Language
  ): Promise<AssistantResponsePayload> {
    return createLocalIcarFallbackResponse(userMessage, farmContext, language, {
      enDisclaimer:
        'CropDiary AI: Provided by verified local ICAR / TNAU agronomic rulebase (offline / rulebase mode).',
      taDisclaimer:
        'பயிர் நாட்குறிப்பு AI: உள்ளூர் ICAR / TNAU வழிகாட்டுதல் அடிப்படையில் பதில் வழங்கப்பட்டுள்ளது (இணையமற்ற முறை).',
    });
  }
}

export const geminiAssistantAdapter = new GeminiAssistantAdapter();
